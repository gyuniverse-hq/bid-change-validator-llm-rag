# -*- coding: utf-8 -*-
"""탐지 어휘 부품 사전 — 문장이 아니라 **문장 형식**에 대응하기 위한 기반.

설계 원칙:
  정규식을 문장 단위로 쓰면 그 문장에만 반응한다. 대신 조항 문장을 구성하는
  **의미 부품**(주체 / 동사 / 대상 / 수식어)을 각각 동의어 목록으로 두고,
  부품을 조합해 패턴을 생성한다. 부품 하나에 동의어를 추가하면 그 부품을
  쓰는 모든 패턴이 함께 넓어진다.

  예: "기타 발주기관이 요구하는 사항"과 "상기 외 감독관이 지시하는 제반 사항"은
      [잔여지시어][주체][재량동사][열린대상]이라는 **같은 형식**이다.
      문장 2개를 외우는 대신 부품 4개를 조합해 둘 다 잡는다.

판정은 여전히 코드가 한다 (절대 원칙). LLM은 여기에 개입하지 않는다.
"""
import re


def alt(items):
    """부품 목록을 비캡처 선택지로 결합."""
    return "(?:" + "|".join(items) + ")"


# 명사 뒤에 올 수 있는 조사. 이걸로 경계를 잡지 않으면 "업무"가
# "업무상의 정보"에 부분 매칭된다 (뒤에 조사가 아닌 한글이 이어지면 다른 단어).
_PARTICLE = r"(?:[을를은는이가의에와과도만]|으?로|까지|부터|에서|이나|나)?(?![가-힣])"


def noun_alt(items):
    """명사 부품 목록 — 조사 경계까지 포함해 결합."""
    return "(?:" + "|".join(items) + ")" + _PARTICLE


# ── 주체: 발주자 측을 가리키는 모든 표현 ─────────────────────────────────
AUTHORITY = [
    r"발주\s*(?:기관|처|자|청|부서)",
    r"수요\s*기관", r"주무\s*관청", r"소관\s*부서",
    r"감독\s*(?:관|원)", r"계약\s*담당\s*(?:공무원|자)?",
    r"공사", r"공단", r"공단측", r"위탁\s*기관",
    # 뒤에 한글이 이어지면 다른 단어다 ("본 사"가 "본 사업"에 걸리는 것 방지)
    r"본\s*(?:기관|원|사|청)(?![가-힣])", r"당\s*(?:기관|원|사|청)(?![가-힣])",
    r"甲", r"갑(?=[에이은가측])",
    r"담당\s*(?:부서|자|공무원)",
]
AUTHORITY_RE = alt(AUTHORITY)

# ── 잔여 지시어: "여기 적힌 것 말고 나머지" ──────────────────────────────
RESIDUAL = [
    r"기타", r"그\s*밖(?:에|의|으로)?", r"그밖(?:에|의)?",
    r"이\s*외(?:에|의)?", r"이외(?:에|의)?", r"그\s*외(?:에|의)?", r"그외(?:에|의)?",
    r"상기\s*외", r"위\s*외", r"전기\s*외", r"이와\s*관련(?:된|하여|하는)",
    r"추가(?:적)?으?로",
]
RESIDUAL_RE = alt(RESIDUAL)

# ── 재량 동사: 발주자 판단으로 범위가 정해짐 ─────────────────────────────
DISCRETION_VERB = [
    r"필요하다고\s*인정(?:하는|하여|되는|하면)",
    r"인정하는", r"요구하는", r"지시하는", r"요청하는",
    r"지정하는", r"판단하는", r"정하는", r"결정하는", r"명하는",
    r"제시하는", r"부여하는",
]
DISCRETION_RE = alt(DISCRETION_VERB)

# ── 열린 대상: 범위가 닫히지 않는 목적어 ─────────────────────────────────
OPEN_OBJECT = [
    r"제반\s*사항", r"모든\s*것", r"일체", r"사항", r"업무", r"과업",
    r"내용", r"작업", r"용역", r"임무",
]
OPEN_OBJECT_RE = noun_alt(OPEN_OBJECT)

# 범위(과업)를 뜻하는 명사만 추린 목록. "일체"·"모든 것"은 제외한다 —
# "손해배상 등 일체의 민·형사상 책임" 같은 법률 상용구까지 잡히기 때문이다.
SCOPE_OBJECT = [r"사항", r"업무", r"과업", r"작업", r"용역", r"임무", r"내용"]
SCOPE_OBJECT_RE = noun_alt(SCOPE_OBJECT)

# ── 부수/수반 표현: 잔여 지시어 없이 범위를 여는 형식 ────────────────────
# '관련'은 일반 문서에 너무 흔해 오탐원이므로 제외한다
ANCILLARY = [r"부수", r"수반", r"파생", r"연관"]
ANCILLARY_RE = alt(ANCILLARY)

# ── 미확정 위임: 지금 정하지 않고 나중에/협의로 ──────────────────────────
DEFERRAL = [
    r"협의(?:하여|를\s*통해|후|\s*후)", r"추후", r"별도(?:로)?", r"차후", r"향후",
]
DEFERRAL_RE = alt(DEFERRAL)
DEFERRAL_VERB = alt([r"정하는", r"정한다", r"결정(?:하는|한다|된다)", r"협의한다", r"협의하여\s*정"])

# ── 지식재산권 관련 부품 ─────────────────────────────────────────────────
IP_NOUN = [
    r"저작재산권", r"저작인격권", r"저작권", r"지식재산권", r"지적재산권",
    r"산업재산권", r"소유권", r"실시권", r"권리",
]
IP_NOUN_RE = alt(IP_NOUN)

PRODUCT = [
    r"산출물", r"결과물", r"성과물", r"계약\s*목적물", r"납품물", r"개발물",
    r"제작물", r"용역\s*목적물",
]
PRODUCT_RE = alt(PRODUCT)

# 단독 귀속을 뜻하는 서술어 (귀속/소유뿐 아니라 보유·이전·양도까지)
SOLE_VERB = [
    r"귀속", r"소유", r"보유", r"이전", r"양도", r"이관", r"승계", r"취득",
]
SOLE_VERB_RE = alt(SOLE_VERB)

# 표준(공동소유·지분균등)에 부합하는 표현 — 이게 있으면 단독귀속 아님
JOINT_OWNERSHIP = [
    r"공동\s*(?:으로\s*)?(?:소유|귀속|보유|개발)",
    r"공유(?:한다|하며|하고|로\s*한다)?",
    r"지분[은이]?\s*균등", r"균등한?\s*지분", r"지분을?\s*균등",
    r"양\s*당사자가?\s*(?:균등|공동)",
    r"각각\s*100분의\s*50", r"각\s*50%",
    # 표준 예규를 그대로 따르겠다고 선언한 문장도 표준 부합으로 본다
    r"(?:용역계약일반조건|계약예규|국가계약법)[^.\n]{0,40}(?:따르|준용|의하|의한다)",
]
JOINT_OWNERSHIP_RE = alt(JOINT_OWNERSHIP)

# ── 하자보수 관련 부품 ───────────────────────────────────────────────────
DEFECT_NOUN = alt([r"하자", r"결함", r"瑕疵", r"불량"])
REPAIR_NOUN = alt([r"보수", r"담보", r"책임", r"수정", r"보증(?!금)"])
FREE_MAINT = alt([r"무상\s*(?:유지\s*)?(?:보수|관리)", r"무상\s*하자", r"무상으?로?"])

# ── 지체상금 관련 부품 ───────────────────────────────────────────────────
DELAY_PENALTY_RE = alt([
    r"지체\s*(?:상금|배상금|보상금)",
    r"지연\s*(?:배상금|손해금|상금|보상금)",
])

# ── 감액/감소 표현 (해지 요건) ───────────────────────────────────────────
DECREASE_RE = alt([
    r"감소", r"축소", r"삭감", r"감액", r"줄어", r"줄인", r"줄이",
    r"감축", r"저감", r"하향",
])

# ── 계약 해제·해지 표현 ─────────────────────────────────────────────────
TERMINATION_RE = alt([r"해지", r"해제", r"해약", r"계약\s*종료"])

# ── 검사·검수 표현 ───────────────────────────────────────────────────────
INSPECTION_RE = alt([r"검사", r"검수", r"인수\s*검사", r"완료\s*검사", r"납품\s*검사"])


def compile_forms(*patterns):
    return [re.compile(p) for p in patterns]
