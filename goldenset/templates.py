# 결함 주입 위치의 정답 조항 라벨 (근거 위치 채점용)
EXPECTED_LABELS = {k: v["clause_label"] for k, v in DEFECT_PHRASINGS.items()}


def inject_defect(text, defect_id, phrasing):
    """조항 라벨로 줄을 찾아 통째로 치환(또는 신설 삽입). 실패 시 None."""
    spec = DEFECT_PHRASINGS[defect_id]
    label = spec["clause_label"]
    lines = text.split("\n")

    insert_after = spec.get("insert_after")
    if insert_after:
        for i, line in enumerate(lines):
            if line.strip().startswith(insert_after + " "):
                lines.insert(i + 1, phrasing["line"])
                return "\n".join(lines)
        return None

    for i, line in enumerate(lines):
        if line.strip().startswith(label + " "):
            lines[i] = phrasing["line"]
            return "\n".join(lines)
    return None
